def _ensure_pg_trgm() -> bool:
    """确保 pg_trgm 扩展就绪（函数）。

    说明：
        菜名模糊搜索索引 idx_recipe_title_trgm 依赖 pg_trgm 的 gin_trgm_ops
        操作符类；本函数先探测扩展可用性（pg_available_extensions），
        可安装则 CREATE EXTENSION，已装/装好返回 True，否则返回 False。
        迁移运行在事务性 DDL 中，绝不让 CREATE EXTENSION 在事务中途抛异常
        （事务 abort 会导致整个迁移不可恢复），与原 create_all 回退语义一致。

    返回值：
        bool：pg_trgm 就绪返回 True；不可用返回 False（跳过 trgm 索引）。

    异常：
        CREATE EXTENSION 因权限失败时向上抛出（明确报错优于静默降级）。
    """
    conn = op.get_bind()
    already = conn.execute(
        sa.text("SELECT count(*) FROM pg_extension WHERE extname = 'pg_trgm'")
    ).scalar()
    if already:
        return True
    installable = conn.execute(
        sa.text("SELECT count(*) FROM pg_available_extensions WHERE name = 'pg_trgm'")
    ).scalar()
    if not installable:
        return False
    # 可安装：执行创建（失败则迁移整体失败，符合「明确报错」约定）
    op.execute("CREATE EXTENSION IF NOT EXISTS pg_trgm")
    return True


