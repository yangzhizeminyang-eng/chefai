# 汇总营养表：既有 + V1.1 新增（键不重叠，均为食材主名）
NUTRITION: dict[str, tuple[float, float, float, float, float]] = {**NUTRITION_BASE, **NUTRITION_V11}


def _validate_seed_data() -> None:
    """种子数据静态自检（模块导入时执行）。

    检查项（任一失败抛 ValueError，阻断 seed 流程，防止脏数据入库）：
        1. INGREDIENTS 主名重复；
        2. category 非法（不在 10 分类内）；
        3. allergen_codes 含八类之外的 code；
        4. verified=False 但 codes 非空（约定：待核实必须 codes 留空）；
        5. ALIASES / NUTRITION 引用了不存在的主名；
        6. 别名与任一主名冲突（同一文本既是主名又是别名会造成检索歧义）；
        7. 同一别名挂在多个食材名下（跨食材重复别名）。

    异常：
        ValueError：上述任一检查未通过，消息中含具体冲突条目。
    """
    names = [row[0] for row in INGREDIENTS]
    name_set = set(names)

    # 1. 主名重复
    dup_names = sorted({n for n in names if names.count(n) > 1})
    if dup_names:
        raise ValueError(f"[seed] 食材主名重复: {dup_names}")

    # 2/3/4. 分类、致敏原 code、verified 约定
    valid_categories = {
        "veg", "meat", "seafood", "egg_milk", "soy",
        "staple", "seasoning", "dry", "frozen", "other",
    }
    valid_allergens = {
        "gluten", "crustacean", "fish", "egg",
        "peanut", "soybean", "milk", "nuts",
    }
    for name, category, codes, verified in INGREDIENTS:
        if category not in valid_categories:
            raise ValueError(f"[seed] 非法分类 {category!r}: {name}")
        bad = [c for c in codes if c not in valid_allergens]
        if bad:
            raise ValueError(f"[seed] 非法致敏原 code {bad}: {name}")
        if not verified and codes:
            raise ValueError(f"[seed] verified=False 但 codes 非空 {codes}: {name}")

    # 5. 别名/营养引用的主名必须存在
    unknown_alias_keys = sorted(set(ALIASES) - name_set)
    if unknown_alias_keys:
        raise ValueError(f"[seed] 别名表引用了不存在的主名: {unknown_alias_keys}")
    unknown_nut_keys = sorted(set(NUTRITION) - name_set)
    if unknown_nut_keys:
        raise ValueError(f"[seed] 营养表引用了不存在的主名: {unknown_nut_keys}")

    # 6. 别名不得与主名冲突
    alias_to_owner: dict[str, str] = {}
    for owner, alias_list in ALIASES.items():
        for alias in alias_list:
            if alias in name_set:
                raise ValueError(f"[seed] 别名 {alias!r} 与主名冲突（挂在 {owner} 下）")
            if alias in alias_to_owner:
                raise ValueError(
                    f"[seed] 别名 {alias!r} 跨食材重复: {alias_to_owner[alias]} 与 {owner}"
                )
            alias_to_owner[alias] = owner


# 模块导入即自检：seed / 测试 / API 引用本模块数据时先拦截脏数据
_validate_seed_data()

