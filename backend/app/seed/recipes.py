def build_recipes(ingredient_map: dict[str, Ingredient]) -> list[Recipe]:
    """将菜谱数据定义转换为 ORM 对象（含食材与步骤关系）。

    说明：
        - 食材用量：数值 → amount_value；(min, max) 元组 → amount_min/amount_max；
        - 致敏原：由所引食材 allergen_codes 取并集（代码自动聚合，任务 2.2 要求）；
        - 菜谱默认 status=published、servings=2、version=1。

    参数：
        ingredient_map：食材名 → Ingredient ORM 对象的映射（须已种入数据库或构造好）。

    返回值：
        list[Recipe]：带 ingredients/steps 关系的 Recipe ORM 对象列表（未入库）。

    异常：
        KeyError：菜谱引用了未定义的食材名时抛出（数据一致性检查）。
    """
    recipes: list[Recipe] = []
    for (title, cuisine, method, difficulty, time_min, kcal, equipment, flags, tips, subs, ing_rows, step_rows) in RECIPES:
        # 致敏原聚合：取所引食材 codes 的并集
        aggregated: set[str] = set()
        recipe = Recipe(
            title=title,
            cuisine=cuisine,
            cooking_method=method,
            difficulty=difficulty,
            time_minutes=time_min,
            servings=2,
            calories_kcal=kcal,
            allergen_codes=sorted(aggregated),  # 占位，下方聚合后回填
            ingredient_allergen_codes=sorted(aggregated),
            dietary_flags=list(flags),
            equipment=list(equipment),
            source_label=SOURCE_LABEL,
            source_license=SOURCE_LICENSE,
            status="published",
            version=1,
            tips=tips,
            substitutes=list(subs),
        )
        # 逐条构造菜谱食材行（用量全量化校验：数值或区间至少其一，CT-6）
        for sort_order, (name, amount, unit, amount_type, note) in enumerate(ing_rows):
            ingredient = ingredient_map.get(name)
            if ingredient is None:
                # 数据一致性兜底：引用不存在食材直接报错，避免脏数据入库
                raise KeyError(f"菜谱「{title}」引用了未定义的食材：{name}")
            aggregated.update(ingredient.allergen_codes or [])
            if isinstance(amount, (tuple, list)):
                row = RecipeIngredient(
                    ingredient_id=ingredient.id,
                    amount_min=amount[0],
                    amount_max=amount[1],
                    amount_unit=unit,
                    amount_note=note,
                    amount_type=amount_type,
                    sort_order=sort_order,
                )
            else:
                row = RecipeIngredient(
                    ingredient_id=ingredient.id,
                    amount_value=amount,
                    amount_unit=unit,
                    amount_note=note,
                    amount_type=amount_type,
                    sort_order=sort_order,
                )
            recipe.ingredients.append(row)
        # 回填聚合后的致敏原（与 ingredient_allergen_codes 同源）
        codes = sorted(aggregated)
        recipe.allergen_codes = codes
        recipe.ingredient_allergen_codes = codes
        # 步骤行
        for step_no, (desc, dur, key_point, failure, hint) in enumerate(step_rows, start=1):
            recipe.steps.append(
                RecipeStep(
                    step_no=step_no,
                    description=desc,
                    duration_seconds=dur,
                    key_point=key_point,
                    failure_tips=failure,
                    amount_hint=hint,
                )
            )
        recipes.append(recipe)
    return recipes
